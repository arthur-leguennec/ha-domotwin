#!/usr/bin/env node
// Regenerates THIRD_PARTY_NOTICES.md from what is really shipped: the Rust crates compiled into the
// WebAssembly modules and the npm packages bundled into the frontend (dev tools are not shipped).
//   node scripts/third-party-notices.mjs
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// The four WebAssembly modules: the engine, the plan import, the 3D model readers and the plan editor.
const crates = ["domotwin-web", "domotwin-import", "domotwin-models", "domotwin-planner"]
  .flatMap((module) =>
    execFileSync(
      "cargo",
      [
        "tree", "-p", module, "--target", "wasm32-unknown-unknown", "-e", "normal",
        "--prefix", "none", "--format", "{p}\t{l}",
      ],
      { cwd: root, encoding: "utf8" },
    ).split("\n"),
  )
  .map((line) => line.replace(/ \(.*\)/, "").trim())
  .filter((line) => line && !line.startsWith("domotwin"))
  .map((line) => {
    const [nameVersion, license] = line.split("\t");
    const [name, version] = nameVersion.split(" ");
    return { name, version: version.replace(/^v/, ""), license: license.replace(/^AND /, "") };
  });
const uniqueCrates = [...new Map(crates.map((c) => [`${c.name}@${c.version}`, c])).values()].sort(
  (a, b) => a.name.localeCompare(b.name),
);

const npmPackages = [];
for (const name of ["lit", "lit-element", "lit-html", "@lit/reactive-element", "@mdi/js"]) {
  const pkg = JSON.parse(
    await readFile(join(root, "frontend", "node_modules", name, "package.json"), "utf8"),
  );
  npmPackages.push({ name: pkg.name, version: pkg.version, license: pkg.license });
}

const table = (rows) =>
  ["| Component | Version | Licence |", "| --- | --- | --- |"]
    .concat(rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`))
    .join("\n");

const text = `# Third-party notices

DomoTwin is MIT-licensed (see [\`LICENSE\`](LICENSE)). It reuses and ships the following works.
This file is generated by \`node scripts/third-party-notices.mjs\`; the licence texts of the
packages are in their source distributions (crates.io, npm).

## Bundled assets

| Asset | Source | Licence |
| --- | --- | --- |
| Demo apartment (\`examples/\`) | Fictional, created for DomoTwin | MIT |
| Figures of \`docs/figures/\` | Drawn for DomoTwin | MIT |
| Materials and textures | None yet; only procedural or CC0 materials will be added, listed here | – |
| Font: Inter 4.1, a subset (\`frontend/fonts/\`, made by \`scripts/subset-font.py\`) | [rsms/inter](https://github.com/rsms/inter), the Inter Project Authors | SIL Open Font License 1.1 (\`frontend/fonts/OFL.txt\`) |

## Rust crates compiled into the WebAssembly modules

${table(uniqueCrates)}

## npm packages bundled into the frontend

${table(npmPackages)}

Icons come from Material Design Icons (\`@mdi/js\`, Pictogrammers).
`;

await writeFile(join(root, "THIRD_PARTY_NOTICES.md"), text);
console.log(`THIRD_PARTY_NOTICES.md: ${uniqueCrates.length} crates, ${npmPackages.length} npm packages`);
